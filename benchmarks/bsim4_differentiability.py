def static_part() -> audit.StaticReport:
    rep = audit.static_report(BSIM4, card(), instance={"w": W, "l": L})
    print(rep.summary())
    default = audit.static_report(BSIM4, card(), differentiable=(),
                                  temperature=vx.va.DEFAULT_TEMPERATURE,
                                  instance={"w": W, "l": L})
    print(f"\nDefault build (model parameters static, W/L traced): "
          f"{len(default.select('branch-on-bias'))} bias-dependent and "
          f"{len(default.select('branch-on-param'))} W/L-dependent sites remain "
          f"as where-merges; generated f/q {default.n_statements[0]}/"
          f"{default.n_statements[1]} statements.")
    path = cm.FIGURES / "bsim4_static_audit.md"
    cm.FIGURES.mkdir(exist_ok=True)
    path.write_text(
        "# BSIM4 static differentiability report\n\n"
        "Generated by `benchmarks/bsim4_differentiability.py` from "
        "`voltax/va/models/bsim4.va` (FreePDK45 NMOS card, all real parameters "
        "and the temperature traced). Line numbers refer to `bsim4.va`.\n\n"
        + rep.summary() + "\n\n## Bias-dependent sites\n\n" +
        rep.table("branch-on-bias") + "\n\n## Parameter-dependent sites\n\n" +
        rep.table("branch-on-param") + "\n\n## Bias-dependent NaN/inf-risk "
        "operations\n\n| line | op | depends on |\n|---|---|---|\n" +
        "\n".join(f"| {n} | {op} | {'+'.join(sorted(d))} |"
                  for _, n, op, d, _ in rep.risks if "bias" in d) + "\n")
    print(f"Wrote {path.relative_to(cm.FIGURES.parent.parent)}")
    return rep


