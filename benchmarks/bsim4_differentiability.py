import numpy as np

import voltax as vx
from voltax.analysis import _dc_residual
from voltax.va import audit

W, L = 0.5e-6, 50e-9
VDD = 1.0
PARAMS = ("vth0", "u0", "toxe", "k1", "vsat", "nfactor", "rdsw", "eta0", "dvt0",
          "voff", "mjs")
BSIM4 = vx.va.load("bsim4")


def card(pol: str = "n", intrinsic: bool = False) -> dict:
    _, _, params = vx.va.bundled_card(f"freepdk45_{pol}mos.inc")
    params = {**vx.va.NGSPICE_BSIM4_DEFAULTS, **params}
    params.pop("level")
    if intrinsic:
        params.update(rbodymod=0, rgatemod=0)
    return params


