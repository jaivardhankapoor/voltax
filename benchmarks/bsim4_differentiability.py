def bias_sweeps(n: int) -> list[tuple]:
    def lin(a, b):
        return np.linspace(a, b, n)  # odd n: symmetric ranges contain 0 exactly

    return [
        ("Vds through 0, Vgs=0.6", "d", lin(-0.3, 0.3), {"g": 0.6}),
        ("Vds through 0, Vgs=1.0", "d", lin(-0.3, 0.3), {"g": 1.0}),
        # with Vbs != 0 the junction switches (vbd = 0 at Vds = Vbs) separate
        # from the source/drain mode swap at Vds = 0
        ("Vds through 0, Vgs=.6 Vbs=-.2", "d", lin(-0.3, 0.3), {"g": 0.6, "b": -0.2}),
        ("Vds 0..1.2, Vgs=1.0", "d", lin(0.0, 1.2), {"g": 1.0}),
        ("Vgs -0.6..1.5, Vds=0.05", "g", lin(-0.6, 1.5), {"d": 0.05}),
        ("Vgs -0.6..1.5, Vds=1", "g", lin(-0.6, 1.5), {"d": 1.0}),
        ("Vbs -1.5..0.8, Vgs=.6 Vds=.5", "b", lin(-1.5, 0.8), {"g": 0.6, "d": 0.5}),
        ("Gummel Vd=-Vs=x, Vgs=0.6", {"d": 1.0, "s": -1.0}, lin(-0.1, 0.1),
         {"g": 0.6}),
    ]


def param_sweeps(n: int, defaults: dict) -> list[tuple]:
    def around(k, lo, hi):
        # always include the card value itself: equality branches such as
        # `if (T != Tnom)` or `if (MJS == 0.5)` trigger exactly there
        return np.unique(np.append(np.linspace(lo, hi, n), defaults[k]))

    return [
        ("vth0", around("vth0", 0.2, 0.7)),
        ("u0", around("u0", 0.02, 0.08)),
        ("toxe", around("toxe", 0.8e-9, 1.6e-9)),
        ("k1", around("k1", 0.1, 0.9)),
        ("vsat", around("vsat", 5e4, 2e5)),
        ("nfactor", around("nfactor", 0.5, 3.0)),
        ("rdsw", around("rdsw", 20.0, 400.0)),  # Rds = 0 is a 0/0 special case
        ("eta0", around("eta0", 0.0, 0.05)),
        ("dvt0", around("dvt0", 0.0, 3.0)),
        ("voff", around("voff", -0.3, 0.0)),
        ("mjs", around("mjs", 0.3, 0.7)),
        ("w", np.unique(np.append(np.geomspace(0.1e-6, 10e-6, n), W))),
        ("l", np.unique(np.append(np.geomspace(30e-9, 2e-6, n), L))),
        ("$temperature", around("$temperature", 233.15, 398.15)),
    ]


def empirical_part() -> dict:
    n = cm.pick(201, 1201)
    probes = {mode: audit.DeviceProbe(BSIM4, card(intrinsic=True),
                                      instance={"w": W, "l": L},
                                      differentiable=PARAMS, temperature=None,
                                      equality=mode)
              for mode in ("value", "limit")}
    rows, results = [], {}
    for name, var, xs, bias in bias_sweeps(n):
        for mode, pr in probes.items():
            r = pr.sweep(var, xs, bias, name=name)
            results[(name, mode)] = r
            rows.append({**r.summary_row(), "mode": mode})
    cols = ["sweep", "mode", "points", "NaN/inf y", "NaN/inf AD", "max |AD-FD|",
            "switch pts", "C0 breaks", "max jump", "C1 breaks", "max slope jump",
            "AD pt errors", "max AD pt err", "unexplained", "lines"]
    cm.print_table([{c: r[c] for c in cols} for r in rows],
                   "Bias sweeps (all 8 terminal currents and charges)")
    describe_events(results)

    prow = []
    for bias_name, bias in (("sat", {"g": 1.0, "d": 1.0}),
                            ("subth", {"g": 0.2, "d": 1.0}),
                            ("lin", {"g": 1.0, "d": 0.05})):
        for var, xs in param_sweeps(cm.pick(81, 401), probes["limit"].P0):
            # the equality-branch parameters in both modes, the rest in 'limit'
            modes = ("value", "limit") if var in ("mjs", "$temperature") else \
                ("limit",)
            for mode in modes:
                r = probes[mode].sweep(var, xs, bias, name=f"{var} @ {bias_name}")
                results[(f"{var} @ {bias_name}", mode)] = r
                prow.append({**r.summary_row(), "mode": mode})
    cm.print_table([{c: r[c] for c in cols if c in r} for r in prow],
                   "Parameter sweeps (all 8 terminal currents and charges)")
    return results


def describe_events(results: dict) -> None:
    """Print the non-smooth switch points of the bias sweeps, with sources."""
    print("\nNon-smooth switch points (bias sweeps, equality='value'):")
    seen = set()
    for (name, mode), r in results.items():
        if mode != "value":
            continue
        for e in r.events:
            for kind in sorted(e.kinds()):
                vals = e.jump0 if kind == "C0 break" else (
                    e.jump1 if kind == "C1 break" else e.point_error)
                worst = sorted(vals.items(), key=lambda kv: -kv[1])[:4]
                key = (name, round(e.x, 9), kind)
                if key in seen:
                    continue
                seen.add(key)
                src = ", ".join(f"{ln}({k})" for ln, k in e.sites)
                print(f"  {name:30s} x={e.x:+.4g}  {kind:14s} "
                      + " ".join(f"{o}={v:.2g}" for o, v in worst)
                      + f"   lines {src}")


