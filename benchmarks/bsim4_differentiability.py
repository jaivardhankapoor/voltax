"""Differentiability audit of BSIM4 compiled from Verilog-A (voltax.va).

1. **Static report**: every conditional / equality branch / clamp / min /
   max / abs the compiler evaluates, compiled with *all* real parameters and
   the temperature traced, classified as static, branch-on-bias or
   branch-on-param (written to ``benchmarks/figures/bsim4_static_audit.md``).
2. **Empirical probes** (`voltax.va.audit.DeviceProbe`, intrinsic device:
   rbodymod=rgatemod=0): fine bias sweeps (Vds through 0, Vgs, Vbs into
   forward bias, the Gummel-symmetry path) and parameter sweeps (VTH0, U0,
   TOXE, ..., W, L, T). For each: NaN/inf in values and AD derivatives, AD vs
   central finite differences, and every branch switch crossed, located by
   bisection and classified (value jump / slope jump / AD point error) with
   the source lines responsible.
3. **Modes**: ``equality="value"`` (plain AD) vs ``"limit"`` (derivative of
   the general branch at ``if (x == c)``), and smooth surrogates for clamps:
   accuracy cost, gradient quality, and Newton iterations from a zero initial
   guess.
4. **End to end**: gradient of a 3-inverter chain delay (`vx.measure.delay`)
   w.r.t. a transistor width and the NMOS VTH0, full card (gate resistor and
   substrate network), against central finite differences.

Run:  uv run python benchmarks/bsim4_differentiability.py   (VOLTAX_FAST=1: coarser)
"""

from __future__ import annotations

import os

os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")  # LAPACK slows badly under load

