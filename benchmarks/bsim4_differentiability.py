# 3. Modes: accuracy, gradient quality, Newton
# =============================================================================

MODES = {
    "exact (value)": dict(equality="value"),
    "limit": dict(equality="limit"),
    "limit + smooth 1e-3": dict(equality="limit", smooth=1e-3),
    "limit + smooth 1e-2": dict(equality="limit", smooth=1e-2),
}


def modes_part() -> list[dict]:
    n = cm.pick(201, 801)
    sweeps = [s for s in bias_sweeps(n) if s[0].startswith(("Vds", "Vgs"))]
    ref = None
    rows = []
    for mode, kw in MODES.items():
        pr = audit.DeviceProbe(BSIM4, card(intrinsic=True), instance={"w": W, "l": L},
                               **kw)
        ys, breaks, pt, fd = [], 0, 0, 0.0
        for name, var, xs, bias in sweeps:
            r = pr.sweep(var, xs, bias, name=name, outputs=("Id", "Ig", "Qg"))
            ys.append(r.y)
            breaks += len(r.breaks("C0 break")) + len(r.breaks("C1 break"))
            pt += len(r.breaks("AD point error"))
            fd = max(fd, r.summary_row()["max |AD-FD|"])
        if ref is None:
            ref = ys
        id_err = max(_rel(y[:, 0], y0[:, 0], 1e-12) for y, y0 in zip(ys, ref))
        id_abs = max(float(np.max(np.abs(y[:, 0] - y0[:, 0])) /
                           np.max(np.abs(y0[:, 0]))) for y, y0 in zip(ys, ref))
        qg_err = max(_rel(y[:, 2], y0[:, 2], 1e-20) for y, y0 in zip(ys, ref))
        id0 = float(pr.functions("d", {"g": 1.0})["y"](np.zeros(1))[0, 0])
        it, fails = newton_counts(kw)
        rows.append({"mode": mode, "max Id rel err": id_err,
                     "max |dId|/max|Id|": id_abs, "Id(Vds=0) (A)": id0,
                     "max Qg rel err": qg_err, "C0+C1 breaks": breaks,
                     "AD point errors": pt, "max |AD-FD|": fd,
                     "Newton its (mean)": float(np.mean(it)),
                     "Newton its (max)": int(np.max(it)), "Newton fails": fails})
    cm.print_table(rows, "Modes: accuracy vs exact, gradient quality, Newton "
                         "iterations from z=0 (inverter VTC points + 3-stage chain)")
    return rows


def _rel(a, b, floor):
    m = np.abs(b) > floor
    return float(np.max(np.abs(a[m] - b[m]) / np.abs(b[m]))) if m.any() else 0.0


def newton_counts(kw: dict) -> tuple[list[int], int]:
    """Iterations of voltax's damped Newton from an all-zero initial guess."""
    nch = BSIM4.element(card("n"), polarity="n", name="nch", **kw)
    pch = BSIM4.element(card("p"), polarity="p", name="pch", **kw)
    its, fails = [], 0
    vins = np.linspace(0.0, VDD, cm.pick(5, 11))
    for stages in (1, 3):
        b = vx.CircuitBuilder()
        b.vsource("vdd", "0", VDD, name="Vdd")
        b.vsource("in", "0", 0.0, name="Vin")
        nodes = ["in"] + [f"n{k}" for k in range(1, stages + 1)]
        for k in range(stages):
            a, y = nodes[k], nodes[k + 1]
            b.add(pch((y, a, "vdd", "vdd"), w=2 * W, l=L), name=f"MP{k}")
            b.add(nch((y, a, "0", "0"), w=W, l=L), name=f"MN{k}")
        c0 = b.build()
        for vin in vins:
            c = c0.set("Vin", value=float(vin))
            _, k, ok = audit.newton_iterations(_residual, c.zeros(), c.n_nodes, c)
            its.append(k)
            fails += not ok
    return its, fails


def _residual(z, c):
    return _dc_residual(z, (c, jnp.asarray(0.0)), 1e-12)


