# 4. End-to-end gradient of a delay
# =============================================================================


def delay_gradient() -> list[dict]:
    rows = []
    t = jnp.arange(0.0, cm.pick(120e-12, 160e-12), 0.25e-12)
    for mode in ("value", "limit"):
        nch = BSIM4.element(card("n"), polarity="n", name="nch",
                            differentiable=("vth0",), equality=mode)
        pch = BSIM4.element(card("p"), polarity="p", name="pch", equality=mode)
        b = vx.CircuitBuilder()
        b.vsource("vdd", "0", VDD, name="Vdd")
        b.vsource("in", "0", vx.signals.Pulse(0.0, VDD, 10e-12, 10e-12, 10e-12,
                                              200e-12, 400e-12), name="Vin")
        nodes = ["in", "n1", "n2", "n3"]
        for k in range(3):
            a, y = nodes[k], nodes[k + 1]
            b.add(pch((y, a, "vdd", "vdd"), w=2 * W, l=L), name=f"MP{k}")
            b.add(nch((y, a, "0", "0"), w=W, l=L), name=f"MN{k}")
            b.capacitor(y, "0", 0.5e-15)
        c = b.build()

        def delay(theta, c=c):
            w, vth0 = theta
            cc = c.set("MN0", w=w)
            group = cc.elements["nch_n"]
            cc = cc.replace("nch_n", group.with_model(vth0=vth0))
            sol = vx.transient(cc, t)
            return vx.measure.delay(sol.t, sol.v("in"), sol.v("n3"), VDD / 2,
                                    trig_direction="rise", targ_direction="fall")

        theta = jnp.array([W, 0.4106])
        (val, grad), first, steady = cm.time_call(
            lambda: jax.value_and_grad(delay)(theta), repeats=1)
        fd = []
        for i, h in enumerate((1e-3 * W, 1e-4)):
            e = jnp.zeros(2).at[i].set(h)
            fd.append(float((delay(theta + e) - delay(theta - e)) / (2 * h)))
        for i, name in enumerate(("W(MN0)", "VTH0 (nch)")):
            rows.append({"equality": mode, "parameter": name,
                         "delay (ps)": float(val) * 1e12,
                         "AD grad": float(grad[i]), "FD grad": fd[i],
                         "rel diff": abs(float(grad[i]) - fd[i]) / abs(fd[i]),
                         "grad time": cm.fmt_s(steady)})
    cm.print_table(rows, "d delay / d theta of a 3-inverter chain (BSIM4 full "
                         "card, transient 0.25 ps grid): AD (adjoint) vs central FD")
    return rows


