def figures(results: dict) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(16, 8.5))
    rv = results[("Vds through 0, Vgs=0.6", "value")]
    rl = results[("Vds through 0, Vgs=0.6", "limit")]
    x = rv.x * 1e3
    zoom = np.abs(rv.x) <= 0.02
    j = rv.outputs.index("Id")
    ax = axes[0, 0]
    ax.plot(x[zoom], rv.dy[zoom, j] * 1e3, "o-", ms=3, label="AD, equality='value'")
    ax.plot(x[zoom], rl.dy[zoom, j] * 1e3, "s--", ms=3, label="AD, equality='limit'")
    ax.plot(x[zoom], rv.dy_fd[zoom, j] * 1e3, "k:", label="central FD")
    ax.set(xlabel="Vds (mV)", ylabel="dId/dVds (mS)",
           title="gds at Vds=0: plain AD of `if (Vds == 0)`")
    ax.legend(fontsize=7)
    for ax, out, label in ((axes[0, 1], "Ig", "dIg/dVds (A/V)"),
                           (axes[0, 2], "Qg", "dQg/dVds (F)")):
        k = rl.outputs.index(out)
        ax.plot(x, rl.dy[:, k], "-", label="AD (limit)")
        ax.plot(x, rl.dy_fd[:, k], "k:", label="FD")
        ax.axvline(0, color="r", lw=0.5)
        ax.set(xlabel="Vds (V) x1e3", ylabel=label,
               title=f"{out}: slope jump at the S/D mode swap")
        ax.legend(fontsize=7)
    g = audit.gummel_symmetry(
        audit.DeviceProbe(BSIM4, card(intrinsic=True), instance={"w": W, "l": L},
                          equality="limit"), vg=0.6, vx_max=0.05, n=cm.pick(201, 801))
    for ax, k, ttl in ((axes[1, 0], "d1", "dIx/dVx"), (axes[1, 1], "d2",
                                                       "d2Ix/dVx2"),
                       (axes[1, 2], "d3", "d3Ix/dVx3")):
        ax.plot(g["vx"] * 1e3, g[k], "-")
        ax.set(xlabel="Vx (mV)  [Vd=+Vx, Vs=-Vx]", title=f"Gummel symmetry: {ttl}")
    for a in axes.ravel():
        a.grid(True, alpha=0.3)
    fig.tight_layout()
    cm.save_figure(fig, "bsim4_audit_vds")

    names = ["vth0 @ sat", "u0 @ sat", "toxe @ sat", "l @ sat", "w @ subth",
             "$temperature @ subth"]
    fig, axes = plt.subplots(2, 3, figsize=(16, 8))
    for ax, name in zip(axes.ravel(), names):
        r = results[(name, "limit")]
        k = r.outputs.index("Id")
        ax.plot(r.x, r.dy[:, k], "-", lw=2, label="AD")
        ax.plot(r.x, r.dy_fd[:, k], "k:", label="FD")
        for e in r.events:
            if e.order() != "C1":
                ax.axvline(e.x, color="r", lw=0.6)
        if name.startswith(("l ", "w ")):
            ax.set_xscale("log")
        ax.set(title=f"dId/d{name}", xlabel=name.split(" @")[0])
        ax.legend(fontsize=7)
        ax.grid(True, alpha=0.3)
    fig.tight_layout()
    cm.save_figure(fig, "bsim4_audit_params")


def main() -> None:
    cm.header("BSIM4 differentiability audit (voltax.va)")
    static_part()
    results = empirical_part()
    figures(results)
    modes_part()
    delay_gradient()


if __name__ == "__main__":
    main()
